    fun flowBytesDigest(): String = FlowXml.write(XmlCorpus.richFlow()).toByteString().sha256().hex()

    fun flowReadDigest(): String {
        val back = TextFlow().also { FlowXml.readInto(it, FlowXml.write(XmlCorpus.richFlow())) }
        return XmlCorpus.flowSummary(back).encodeUtf8().sha256().hex()
    }

    /** Null when the SVG scene matches the JVM's, else what differs. */
    fun sceneMismatch(): String? {
        val summary = XmlCorpus.sceneSummary(SvgReader.parse(XmlCorpus.svg.encodeToByteArray()))
        val shape = XmlCorpus.sceneShape(summary).encodeUtf8().sha256().hex()
        if (shape != SCENE_SHAPE) return "scene structure differs: $shape\n$summary"
        val expected = SCENE_NUMBERS.split(' ').map { it.toDouble() }
        val actual = XmlCorpus.sceneNumbers(summary)
        if (expected.size != actual.size) return "${actual.size} numbers, expected ${expected.size}"
        for (i in expected.indices) {
            val e = expected[i]
            val a = actual[i]
            if (abs(e - a) > 1e-6 * maxOf(1.0, abs(e))) return "number #$i: $a, expected $e"
        }
        return null
    }
